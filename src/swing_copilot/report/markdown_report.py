class LatestMarkdownUpdateError(SwingCopilotError, OSError):
    """The immutable run archive exists, but `latest.md` could not be updated."""

    def __init__(self, report_path: Path, cause: OSError) -> None:
        """Keep the durable archive path while preserving the write failure."""
        super().__init__(str(cause))
        self.report_path = report_path


def render_markdown(brief: DailyBrief, status: RunStatus) -> str:
    """Render a generated, human-readable audit snapshot."""
    lines = [
        "<!-- Generated by swing-copilot; DuckDB is the source of truth. -->",
        "",
        f"# Swing Copilot — {brief.run_date.isoformat()}",
        "",
        f"- Status: `{status.value}`",
        f"- Run ID: `{brief.run_id}`",
        f"- Generated at: `{brief.generated_at.isoformat()}`",
        f"- Data provider: `{brief.provider_name}`",
        _data_tier_disclosure(brief.data_tier),
        "",
    ]
    if brief.no_trade:
        reason = f"（{brief.no_trade_reason}）" if brief.no_trade_reason else ""
        lines.extend([f"> **{NO_TRADE_MESSAGE}**{reason}", ""])
    lines.extend(
        [
            "## Market",
            "",
            "| Symbol | Value | Change |",
            "|---|---:|---:|",
        ]
    )
    lines.extend(
        f"| {item.label} | {_number(item.value)} | {_percent(item.pct_change)} |"
        for item in brief.market
    )
    if brief.regime is not None:
        lines.extend(
            [
                "",
                "## Market regime",
                "",
                f"- Gate: `{brief.regime.gate}`",
                f"- Trend: SPY close {_number(brief.regime.spy_close)} / SMA200 {_number(brief.regime.spy_sma200)} ({_percent(brief.regime.spy_trend_gap_pct)})",
                f"- Distribution Day level: `{brief.regime.dd_level}`",
                f"- SPY d25: {brief.regime.spy_d25:g}; QQQ d25: {brief.regime.qqq_d25:g}",
                f"- Data quality: `{brief.regime.data_quality}`",
            ]
        )
        if brief.regime.spy_ftd_state is not None:
            lines.extend(
                [
                    f"- FTD SPY: `{brief.regime.spy_ftd_state}`{_ftd_suffix(brief.regime.spy_ftd_day_number, brief.regime.spy_ftd_quality_score)}",
                    f"- FTD QQQ: `{brief.regime.qqq_ftd_state}`{_ftd_suffix(brief.regime.qqq_ftd_day_number, brief.regime.qqq_ftd_quality_score)}",
                ]
            )
    if brief.exposure is not None:
        downgrade = (
            "（保守的降格）" if brief.exposure.is_conservatively_downgraded else ""
        )
        lines.extend(
            [
                "",
                "## Exposure Ceiling",
                "",
                f"- Verdict: `{brief.exposure.verdict}` {downgrade}",
                f"- Inputs: gate `{brief.exposure.gate}`, DD `{brief.exposure.dd_level}`",
                f"- Data quality: `{brief.exposure.data_quality}`",
            ]
        )
        if brief.exposure.verdict == "REDUCE_ONLY":
            lines.extend(
                [
                    "",
                    "## 相場は警戒状態\uff1a新規は控えめに",
                    "",
                    f"- 理由: Gate `{brief.exposure.gate}` / DD `{brief.exposure.dd_level}`",
                ]
            )
    lines.extend(_candidates_section(brief.candidates))
    lines.extend(_tracking_section(brief.tracked))
    for candidate in brief.candidates:
        lines.extend(_candidate_section(candidate))
    lines.extend(["", "## 落選サマリ", ""])
    if brief.rejection_counts:
        lines.extend(["| reason_code | 件数 |", "|---|---:|"])
        lines.extend(
            f"| {item.reason_code} | {item.count} |" for item in brief.rejection_counts
        )
    else:
        lines.append("該当なし(0件)")
    lines.extend(["", "## シグナル成績（直近90日）", ""])
    if brief.signal_performance:
        lines.extend(
            [
                "| Signal | TP | FP | NEUTRAL | 的中率 | N |",
                "|---|---:|---:|---:|---:|---:|",
            ]
        )
        lines.extend(_signal_performance_row(row) for row in brief.signal_performance)
    else:
        lines.append("該当なし(0件)")
    if brief.notices:
        lines.extend(["", "## Warnings", ""])
        lines.extend(f"- {notice}" for notice in brief.notices)
    lines.extend(["", "---", "", _DISCLAIMER, ""])
    return "\n".join(lines)


def write_markdown_report(
    brief: DailyBrief, status: RunStatus, output_dir: str | Path
) -> Path:
    """Write a run-ID archive and `latest.md` using atomic replacement."""
    root = Path(output_dir)
    dated_dir = root / brief.run_date.isoformat()
    dated_dir.mkdir(parents=True, exist_ok=True)
    content = render_markdown(brief, status)
    report_path = dated_dir / f"{brief.run_id}.md"
    write_text_atomically(report_path, content)
    try:
        write_text_atomically(root / "latest.md", content)
    except OSError as exc:
        raise LatestMarkdownUpdateError(report_path, exc) from exc
    return report_path


def _data_tier_disclosure(data_tier: str) -> str:
    if data_tier == "prototype":
        return "- Data tier: `prototype`（非公式データに基づく試作結果）"
    return f"- Data tier: `{data_tier}`"


def _candidates_section(candidates: tuple[BriefCandidate, ...]) -> list[str]:
    """P6-28: one self-contained table per P5-23 execution bucket.

    Each bucket gets its own heading, header row, separator row, and data
    rows in sequence, rather than a single table interrupted midstream by
    bucket headings -- the latter breaks Markdown table rendering because a
    heading between the header/separator and the data rows ends the table.
    """
    lines = ["", "## Candidates"]
    cash_priority = any(
        execution_bucket(candidate.execution_state, risk_reasons=candidate.risk.reasons)
        == EXECUTION_CASH_PRIORITY_BUCKET
        for candidate in candidates
    )
    buckets = (
        *EXECUTION_BUCKETS[:2],
        *((EXECUTION_CASH_PRIORITY_BUCKET,) if cash_priority else ()),
        EXECUTION_BUCKETS[2],
    )
    for bucket in buckets:
        bucket_candidates = [
            candidate
            for candidate in candidates
            if execution_bucket(
                candidate.execution_state, risk_reasons=candidate.risk.reasons
            )
            == bucket
        ]
        lines.extend(["", f"### {bucket}", ""])
        if not bucket_candidates:
            lines.append("該当なし")
            continue
        lines.extend(
            [
                "| Rank | Symbol | Close | Change | RSI14 | Score | Execution | Signals | Risk | 1R | Stop | Limit |",
                "|---:|---|---:|---:|---:|---:|---|---|---|---:|---:|---:|",
            ]
        )
        lines.extend(_candidate_row(candidate) for candidate in bucket_candidates)
    return lines


def _candidate_row(candidate: BriefCandidate) -> str:
    return (
        "| "
        + " | ".join(
            (
                str(candidate.rank),
                candidate.symbol,
                _money(candidate.close),
                _percent(candidate.pct_change),
                _number(candidate.rsi14, digits=1),
                _number(candidate.score, digits=3),
                _execution_state_text(candidate),
                ", ".join(candidate.signals) or "-",
                candidate.risk.status,
                _one_r(candidate.risk.stop_distance_pct),
                _money(candidate.risk.stop_price),
                _money(candidate.risk.limit_price),
            )
        )
        + " |"
    )


def _tracking_section(rows: tuple[BriefTrackedRow, ...]) -> list[str]:
    """Render the proceed-only public tracking board."""
    lines = ["", "## 追跡中の推奨", ""]
    if not rows:
        lines.append("該当なし(0件)")
        return lines
    lines.extend(
        [
            "| 銘柄 | 推奨日 | 推奨時終値 | 現在値 | 損益 | 本日の逆指値 | 状態 | 残り営業日 |",
            "|---|---|---:|---:|---:|---:|---|---:|",
        ]
    )
    lines.extend(
        "| "
        + " | ".join(
            (
                row.symbol,
                row.entry_date.isoformat(),
                _money(row.entry_price),
                _money(row.last_close),
                _tracking_return(row.unrealized_return_pct),
                _money(row.stop_price),
                _tracking_status(row),
                _tracking_days(row.days_remaining),
            )
        )
        + " |"
        for row in rows
    )
    return lines


def _tracking_return(value: float | None) -> str:
    return "N/A" if value is None else f"{value:+.2f}%"


def _tracking_days(value: int | None) -> str:
    return "—" if value is None else str(value)


def _tracking_status(row: BriefTrackedRow) -> str:
    if row.status != "closed":
        return "追跡中"
    labels = {"stop": "ストップ到達で終了", "max_hold": "時間切れで終了"}
    label = labels.get(row.exit_reason or "", "終了")
    if row.exit_date is None:
        return label
    return f"{label}（{row.exit_date.month}/{row.exit_date.day}）"


def _candidate_section(candidate: BriefCandidate) -> list[str]:
    analysis = candidate.analysis
    verdict_line = format_verdict(analysis)
    lines = [
        "",
        f"## {candidate.symbol}",
        "",
        f"- Company: {candidate.company_name or 'N/A'}",
        f"- 定性: {analysis.conclusion}",
        # Placed directly under the conclusion it qualifies, and only when a
        # verified verdict exists -- silence must never read as "懸念なし".
        *([f"- {verdict_line}"] if verdict_line is not None else []),
        f"- Fundamentals: PER {candidate.fundamentals.per}, FCF {candidate.fundamentals.fcf}, "
        f"Equity ratio {candidate.fundamentals.equity_ratio}, EPS {candidate.fundamentals.eps}",
    ]
    lines.extend(_news_supply_lines(candidate))
    lines.extend(f"- Risk: {reason}" for reason in candidate.risk.reasons)
    lines.extend(f"- Warning: {warning}" for warning in candidate.risk.warnings)
    lines.extend(_score_breakdown_section(candidate))
    lines.extend(_screening_assessment_section(candidate))
    if analysis.facts:
        lines.extend(["", "### Facts", ""])
        lines.extend(f"- {fact}" for fact in analysis.facts)
    if analysis.risk_flags:
        lines.extend(["", "### 定性リスクフラグ", ""])
        lines.extend(f"- {flag}" for flag in analysis.risk_flags)
    if analysis.sources:
        lines.extend(["", "### Sources", ""])
        lines.extend(
            f"- [{source.source_id}]({source.url})" for source in analysis.sources
        )
    lines.extend(_filing_analysis_sections(candidate))
    return lines


def _news_supply_lines(candidate: BriefCandidate) -> list[str]:
    """Issue #281: state, in code-owned text, why the news read the way it did.

    AC14 and `analyze-news/SKILL.md` keep `news_summary: null` whenever
    `news[]` is empty, which erases the difference between "suppressed"
    (`level` none/sparse over a *non-empty* collected set -- news exists but
    hardly any of it names the company, the J.B. Hunt scenario from Issue
    #130) and "genuinely zero" (`collected_items == 0` -- nothing was
    collected at all). This line draws that distinction from the
    deterministic counts alone, independent of anything the skill wrote.

    Omitted entirely when `news_supply` was never measured (an
    `analysis-input-v2`/pre-#130 document, or an analysis that is still
    pending/withheld/missing), matching this file's style for optional
    per-candidate subsections.
    """
    supply = candidate.analysis.news_supply
    if supply is None:
        return []
    return [f"- News supply: {_news_supply_text(supply)}"]


def _news_supply_text(supply: BriefNewsSupply) -> str:
    counts = (
        f"level: {supply.level}, collected_items: {supply.collected_items}, "
        f"exported_items: {supply.exported_items}, "
        f"symbol_mention_items: {supply.symbol_mention_items}"
    )
    if supply.collected_items == 0:
        return f"そもそもニュースが収集されていません（{counts}）"
    if supply.level in ("none", "sparse"):
        return f"本銘柄への言及が乏しく抑制されました（{counts}）"
    return f"本銘柄への言及があるニュースが十分に収集されています（{counts}）"


def _screening_assessment_section(candidate: BriefCandidate) -> list[str]:
    """Strengths/concerns from the qualitative screening assessment.

    Omitted entirely when the analysis is pending or withheld, matching this
    file's style for optional per-candidate subsections.
    """
    analysis = candidate.analysis
    if not analysis.strengths and not analysis.concerns:
        return []
    lines = ["", "### 定性評価", ""]
    lines.extend(f"- 強み: {item}" for item in analysis.strengths)
    lines.extend(f"- 懸念: {item}" for item in analysis.concerns)
    return lines


def _filing_analysis_sections(candidate: BriefCandidate) -> list[str]:
    """One identified subsection per filing analysis (form type + filed date).

    Every filing analysis for this candidate is shown, individually labeled so
    which disclosure a fact/interpretation came from is clear. Both labels are
    code-owned metadata resolved from `analysis_input.json`.
    """
    lines: list[str] = []
    for filing in candidate.analysis.filings:
        lines.extend(
            [
                "",
                f"### 開示分析: {filing.filing_type} ({filing.filed_at.isoformat()})",
                "",
            ]
        )
        lines.extend(f"- Fact: {fact}" for fact in filing.facts)
        lines.extend(f"- Interpretation: {text}" for text in filing.interpretation)
        lines.extend(f"- Red flag: {flag}" for flag in filing.red_flags)
        lines.extend(f"- YoY change: {change}" for change in filing.yoy_changes)
        lines.extend(
            f"- Source: [{source.source_id}]({source.url})" for source in filing.sources
        )
    return lines


#: The weighted components rendered under a candidate's score, in the order
#: `config.ScoreWeights` declares them. All-or-nothing: a missing component
#: suppresses the whole table (see `_score_breakdown_section`).
_SCORE_BREAKDOWN_COMPONENTS = (
    "rsi_pullback",
    "trend_quality",
    "liquidity",
    "atr_pct",
    "pivot_proximity",
    "rs_percentile",
    "criteria_met",
)


def _score_breakdown_section(candidate: BriefCandidate) -> list[str]:
    """REQ-008: a per-candidate table of the composite score's weighted components."""
    values = [
        getattr(candidate, f"score_{name}") for name in _SCORE_BREAKDOWN_COMPONENTS
    ]
    if candidate.score is None or any(value is None for value in values):
        return []
    return [
        "",
        "### Score breakdown",
        "",
        f"- Total: {candidate.score:.3f}",
        "",
        "| Component | Weighted value |",
        "|---|---:|",
        *(
            f"| {name} | {value:.3f} |"
            for name, value in zip(_SCORE_BREAKDOWN_COMPONENTS, values, strict=True)
        ),
    ]


def _signal_performance_row(row: SignalPerformanceRow) -> str:
    """P2-11: one "シグナル成績" table row, with a `(暫定)` marker under REQ-030."""
    hit_rate = _percent(row.hit_rate)
    if row.is_preliminary:
        hit_rate += " (暫定)"
    return (
        f"| {row.signal_name} | {row.true_positive_count} | "
        f"{row.false_positive_count} | {row.neutral_count} | {hit_rate} | {row.n} |"
    )


def _number(value: float | None, *, digits: int = 2) -> str:
    return "N/A" if value is None else f"{value:,.{digits}f}"


def _execution_state_text(candidate: BriefCandidate) -> str:
    """Render the code-owned P5-23 state and ATR-normalized distance."""
    if (
        execution_bucket(candidate.execution_state, risk_reasons=candidate.risk.reasons)
        == EXECUTION_CASH_PRIORITY_BUCKET
    ):
        return EXECUTION_CASH_PRIORITY_BUCKET
    if candidate.execution_distance is None:
        return f"{candidate.execution_state} (d=N/A)"
    return f"{candidate.execution_state} (d={candidate.execution_distance:.2f})"


def _money(value: float | None) -> str:
    return "N/A" if value is None else f"${value:,.2f}"


def _one_r(value: float | None) -> str:
    return "N/A" if value is None else f"{value:.2%}"


def _percent(value: float | None) -> str:
    return "N/A" if value is None else f"{value:+.2%}"


def _ftd_suffix(day_number: int | None, score: int | None) -> str:
    values = []
    if day_number is not None:
        values.append(f"Day{day_number}")
    if score is not None:
        values.append(f"品質スコア {score}")
    return f"（{'、'.join(values)}）" if values else ""
